/** Translate a canonical API state for display without changing its stored value. */
export function translateStatus(status: string): string {
  const code = status.toUpperCase();
  const key = statusMessageKeys[code];
  if (key) return translate(activeLocale, key);
  const source = code.replace(/_/g, ' ').toLowerCase();
  return tx(source.replace(/^\p{L}/u, (first) => first.toUpperCase()));
}

